async def test_deadline_is_checked_between_images_not_only_between_posts():
    """One post with several slow images must not run past the window alone."""
    alpha = (FIXTURES / "alpha.png").read_bytes()
    responses = {f"https://img/{i}.png": alpha for i in range(4)}
    hasher, fetcher = _hasher(responses, deadline_seconds=0.01)

    slow = fetcher

    async def slow_fetch(url: str) -> bytes:
        await asyncio.sleep(0.05)
        return await _Fetcher.__call__(slow, url)

    hasher._fetcher = slow_fetch
    await hasher.hash_posts([_post(*responses)])
    assert len(fetcher.calls) == 1, "the deadline expired after the first image"


