def test_hash_survives_area_downscaling():
    """Invariance to resampling is what makes thumbnail fetching legitimate."""
    large = decode_luma(_png_bytes(_pattern(256)))
    small = resample(large, 64)
    assert hamming_distance(perceptual_hash(large), perceptual_hash(small)) == 0


def test_hash_ignores_brightness_and_contrast():
    """The median threshold is what buys this; without it, exposure moves bits."""
    base = decode_luma(_png_bytes(_pattern(128))).astype(np.float64)
    dimmed = base * 0.55 + 20.0
    assert hamming_distance(perceptual_hash(base), perceptual_hash(dimmed)) == 0


def test_hamming_distance_refuses_incomparable_digests():
    assert hamming_distance("ab", "abcd") is None
    assert hamming_distance("zz", "00") is None


def test_perceptual_values_excludes_exact_hashes():
    mixed = [perceptual_label("00ff00ff00ff00ff"), exact_label("Mx4k4ymW"), "", "bare"]
    assert perceptual_values(mixed) == ["00ff00ff00ff00ff"]


def test_cluster_by_distance_is_single_linkage():
    """A drifts to B drifts to C: one lineage even though A and C are far apart."""
    a = 0
    b = 0b111111 << 20
    c = 0b111111_111111 << 20
    chain = [f"{v:016x}" for v in (a, b, c)]
    assert hamming_distance(chain[0], chain[2]) == 12
    assert len(set(cluster_by_distance(chain, 6))) == 1
    assert len(set(cluster_by_distance(chain, 5))) == 3


def test_cluster_labels_are_dense_and_ordered():
    hashes = [_hash("alpha.png"), _hash("beta.png"), _hash("alpha_small.jpg")]
    assert cluster_by_distance(hashes, 6) == [0, 1, 0]


