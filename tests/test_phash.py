def _load(name: str) -> np.ndarray:
    return decode_luma((FIXTURES / name).read_bytes())


def _hash(name: str) -> str:
    return perceptual_hash(_load(name))


def _png_bytes(array: np.ndarray, *, filters: tuple[int, ...] = (0,)) -> bytes:
    """Minimal 8-bit RGB PNG encoder, so tests can synthesize images.

    `filters` cycles the scanline filter type, which is the only way to reach
    the decoder's Sub/Up/Average/Paeth paths deliberately — a real encoder picks
    them adaptively and may never emit the one that is broken.
    """
    height, width, _ = array.shape
    bpp = 3
    lines: list[bytes] = []
    prior = bytearray(width * bpp)
    for row in range(height):
        ftype = filters[row % len(filters)]
        line = bytearray(array[row].tobytes())
        lines.append(bytes([ftype]) + _apply_png_filter(line, prior, ftype, bpp))
        prior = line

    def chunk(name: bytes, body: bytes) -> bytes:
        payload = name + body
        return struct.pack(">I", len(body)) + payload + struct.pack(">I", zlib.crc32(payload))

    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(b"".join(lines), 6))
        + chunk(b"IEND", b"")
    )


def _apply_png_filter(line: bytearray, prior: bytearray, ftype: int, bpp: int) -> bytes:
    """The forward direction of RFC 2083's five filters."""
    out = bytearray(len(line))
    for i in range(len(line)):
        left = line[i - bpp] if i >= bpp else 0
        upleft = prior[i - bpp] if i >= bpp else 0
        predictor = {
            0: 0,
            1: left,
            2: prior[i],
            3: (left + prior[i]) >> 1,
            4: _paeth_predictor(left, prior[i], upleft),
        }[ftype]
        out[i] = (line[i] - predictor) & 0xFF
    return bytes(out)


def _paeth_predictor(a: int, b: int, c: int) -> int:
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    return b if pb <= pc else c


def _pattern(size: int, phase: float = 0.0) -> np.ndarray:
    grid_y, grid_x = np.mgrid[0:size, 0:size].astype(float)
    values = 128 + 100 * np.sin(grid_x / (size / 12.0) + phase) * np.cos(grid_y / (size / 9.0))
    return np.dstack([values, values, values]).clip(0, 255).astype(np.uint8)


