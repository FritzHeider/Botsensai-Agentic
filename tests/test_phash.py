def test_png_and_jpeg_of_the_same_picture_agree():
    """The DC-only JPEG path must land where the full PNG decode lands."""
    assert hamming_distance(_hash("alpha.png"), _hash("alpha_full.jpg")) == 0
    assert hamming_distance(_hash("beta.png"), _hash("beta.jpg")) == 0


@pytest.mark.parametrize(
    "name",
    ["alpha_restart.jpg", "alpha_gray.jpg", "alpha_444.jpg", "alpha_progressive.jpg"],
)
def test_jpeg_encoder_options_do_not_move_the_hash(name):
    """Restart intervals, greyscale, 4:4:4 chroma and progressive are all in the wild."""
    assert hamming_distance(_hash("alpha.png"), _hash(name)) == 0


def test_progressive_jpeg_is_decoded_not_refused():
    """Measured 2026-08-04: every image pbs.twimg.com served was progressive.

    A decoder that refuses them produces exactly zero coverage on X, which is
    the surface most of the social family depends on.
    """
    decoded = _load("alpha_progressive.jpg")
    assert decoded.shape == (32, 32)
    assert np.abs(decoded - resample(_load("alpha.png"), 32)).mean() < 4.0


def test_progressive_jpeg_without_a_leading_dc_scan_is_refused():
    """Reordered scans would need the AC passes this decoder exists to skip."""
    data = bytearray((FIXTURES / "alpha_progressive.jpg").read_bytes())
    marker = data.index(b"\xff\xda")
    length = int.from_bytes(data[marker + 2 : marker + 4], "big")
    # Ss lives after the per-component table bytes; move the scan off DC.
    data[marker + 2 + length - 3] = 1
    with pytest.raises(UnsupportedImage, match="leading DC scan"):
        decode_luma(bytes(data))


def test_arithmetic_and_lossless_frames_are_refused():
    data = bytearray((FIXTURES / "alpha_full.jpg").read_bytes())
    data[data.index(b"\xff\xc0") + 1] = 0xC9  # SOF9, arithmetic coding
    with pytest.raises(UnsupportedImage, match="unsupported jpeg frame"):
        decode_luma(bytes(data))


def test_jpeg_shape_is_one_eighth_scale():
    """DC-only decoding yields one sample per 8x8 block, by construction."""
    assert _load("alpha_full.jpg").shape == (32, 32)
    assert _load("alpha.png").shape == (256, 256)


