@pytest.mark.parametrize("ftype", [0, 1, 2, 3, 4])
def test_every_png_scanline_filter_round_trips(ftype):
    """All five filters, each one used for every row, decoded exactly.

    Real encoders choose adaptively, so a fixture can leave a filter — Average
    in practice — never exercised while the file still decodes perfectly.
    """
    array = _pattern(48)
    decoded = decode_luma(_png_bytes(array, filters=(ftype,)))
    expected = array.astype(np.float64) @ np.array([0.299, 0.587, 0.114])
    assert np.abs(decoded - expected).max() < 1e-4


def test_png_with_mixed_filters_round_trips():
    array = _pattern(48)
    decoded = decode_luma(_png_bytes(array, filters=(0, 1, 2, 3, 4)))
    expected = array.astype(np.float64) @ np.array([0.299, 0.587, 0.114])
    assert np.abs(decoded - expected).max() < 1e-4


@pytest.mark.parametrize(
    ("name", "tolerance"),
    [
        ("alpha_filtered.png", 0.001),  # adaptive Sub/Up/Paeth filtering
        ("alpha_16bit.png", 0.001),  # 16-bit channels, high byte taken
        ("alpha_grayscale.png", 2.0),  # colour type 0
        ("alpha_palette.png", 3.0),  # colour type 3, quantised to 64 colours
    ],
)
def test_png_colour_types_and_depths_agree(name, tolerance):
    """Same hash *and* the same numbers.

    The hash is blind to any global scaling of the luma plane, so a hash-only
    assertion would let a channel-slicing bug through — misreading 16-bit RGB as
    8-bit yields 0.89R + 0.11G, which is a different picture that happens to
    hash the same.
    """
    assert hamming_distance(_hash("alpha.png"), _hash(name)) == 0
    assert np.abs(_load(name) - _load("alpha.png")).mean() < tolerance


@pytest.mark.parametrize("name", ["alpha_full.jpg", "alpha_restart.jpg"])
def test_jpeg_luma_matches_the_png_it_was_encoded_from(name):
    """The DC quantisation factor and the +128 level shift, pinned numerically.

    `alpha_restart.jpg` carries a luma quantisation of 10 against
    `alpha_full.jpg`'s 1, so only the pair together can tell a decoder that
    applies the quantisation table from one that ignores it.
    """
    reference = resample(_load("alpha.png"), 32)
    decoded = _load(name)
    assert decoded.shape == reference.shape
    assert np.abs(decoded - reference).mean() < 4.0
    assert abs(float(decoded.mean()) - float(reference.mean())) < 2.0


