class _Body:
    def __init__(self, chunks: list[bytes]) -> None:
        self.chunks = chunks
        self.status_code = 200
        self.delivered = 0

    async def aiter_bytes(self):
        for chunk in self.chunks:
            self.delivered += len(chunk)
            yield chunk


async def test_byte_cap_stops_the_transfer_rather_than_truncating():
    """Truncated JPEG bytes can still decode, into a picture nobody posted."""
    hasher, _ = _hasher({}, max_bytes=1000)
    body = _Body([b"x" * 400] * 10)

    with pytest.raises(Exception, match="exceeds 1000 bytes"):
        await hasher._read_capped(body)
    # Stopped as soon as the cap was crossed, not after draining the response.
    assert body.delivered == 1200


async def test_empty_body_is_a_failure_not_an_absence():
    hasher, _ = _hasher({}, max_bytes=1000)
    with pytest.raises(Exception, match="empty body"):
        await hasher._read_capped(_Body([]))


async def test_pipeline_hashes_posts_before_they_are_written(tmp_path):
    """The store has no key to come back with, so this is the only chance.

    `insert_posts` is the single path into the store, and a post row is keyed by
    (platform, post_id) with no route back from a URL — hashing after the write
    would mean the hashes never land.
    """
    from botsensai.collectors.base import CollectionResult
    from botsensai.config import load_settings
    from botsensai.pipeline import Pipeline
    from botsensai.store.db import Database
    from botsensai.util.synthetic import generate_token

    settings = load_settings()
    settings.db_path = str(tmp_path / "media.db")
    pipeline = Pipeline(settings, db=Database(settings.db_path), collectors=[])
    launch = generate_token("organic", seed=3).launch

    post = _post("https://img/a.png")
    post.token_key = launch.token.key
    harvested = CollectionResult(
        surface="x",
        started_at=datetime.fromisoformat("2026-08-01T00:00:00+00:00"),
        finished_at=datetime.fromisoformat("2026-08-01T00:00:01+00:00"),
        posts=[post],
    )

    async def fake_sweep(tokens):
        return [harvested]

    order: list[str] = []

    async def fake_hash(posts):
        order.append("hash")
        for p in posts:
            p.media_hashes.append(perceptual_label("dead" * 4))
        return len(posts)

    original_insert = pipeline.db.insert_posts

    def spy_insert(posts):
        order.append("insert")
        # The point of the ordering: the row that reaches the store carries it.
        assert all(perceptual_values(p.media_hashes) for p in posts)
        return original_insert(posts)

    pipeline.collectors.sweep_enrich = fake_sweep
    pipeline.media_hasher.hash_posts = fake_hash
    pipeline.db.insert_posts = spy_insert

    await pipeline.enrich([launch])
    assert order == ["hash", "insert"]


