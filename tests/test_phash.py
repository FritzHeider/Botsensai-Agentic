def test_resized_and_reencoded_copy_hashes_close():
    """256px lossless PNG vs a 96px JPEG at quality 35 — same picture, ~1/7 the pixels."""
    distance = hamming_distance(_hash("alpha.png"), _hash("alpha_small.jpg"))
    assert distance is not None and distance <= 6, distance


def test_unrelated_image_is_not_close():
    distance = hamming_distance(_hash("alpha.png"), _hash("beta.png"))
    assert distance is not None and distance > 6, distance
    # Independent 64-bit hashes sit near 32; anything much below that would mean
    # the hash is collapsing distinct pictures together.
    assert distance >= 20, distance


